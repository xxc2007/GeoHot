-- 把 `llm` 这道门的熔断窗回写成线上现值：300/6,000/40,000 → 8/420/6,000
--
-- 怎么发现的（不是读代码读出来的，是量出来的）：2026-10-12 用仓库里的 62 个迁移在本地建了一库
-- （`geohot_budgets_ci`，一次性库），把它的 `budgets` 与线上逐行对比。15 行里 14 行相等，
-- 只有 `llm` 不相等：**线上 8/420/6,000，而按迁移重建出来的库是 0036 当初种下的 300/6,000/40,000**。
-- 也就是说这道窗是在服务器上手工 UPDATE 过的，从来没有回写成迁移。
--
-- 为什么 8 是对的：`0065` 那份注释里已经记了实测——近 3 小时逐分钟统计，llm 在最忙的一分钟正好是
-- 8/8（顶满自设窗），且 152 次尝试只有 28 次答出（18%），这个应答率说明 8/分就是**对端的墙**，
-- 不是我们保守。线上现值就是这个墙位。
--
-- 不修的后果：本站是照着"可随时迁移部署"做的（`deploy/geohot/portable-backup.sh` 出的包 + 这套迁移），
-- 一次恢复演练或换机重建库，就会把这道门静默抬到 300/分＝对端墙的 37 倍。429 本身不吃小时窗与日窗，
-- 所以报表不会喊疼，疼的是每一次撞墙都要占住一个 worker 槽位等回包，以及 `sickServices` 会把整道门
-- 板凳掉——表现是"网站突然不再更新"，而原因藏在一份没人再看的旧迁移里。
--
-- 这条也说明 `0036` 不能改：它已经在线上库应用过了，`schema_migrations` 按文件名记账，
-- 改旧文件不会重跑，只会让"文件说的"和"库里的"更对不上。所以按前向迁移的规矩来。
--
-- 回滚：UPDATE budgets SET per_minute=300, per_hour=6000, per_day=40000 WHERE service='llm';
-- 但退回之前请先重新量一次对端墙——上面那两个数（8/8 顶满、18% 应答）是 2026-10-12 的读数。
INSERT INTO budgets (service, per_minute, per_hour, per_day, note) VALUES
  ('llm', 8, 420, 6000, '模型调用熔断（默认模型，所有步骤共用）。8/分是实测对端墙：2026-10-12 逐分钟统计里这一门最忙的一分钟正好 8/8，且 152 试 28 答（18%）。此值原先只在服务器上 UPDATE 过、没回写成迁移，本迁移补上这段差——按 0036 重建库会得到 300/分＝墙位的 37 倍）')
ON CONFLICT (service) DO UPDATE SET per_minute = EXCLUDED.per_minute, per_hour = EXCLUDED.per_hour,
  per_day = EXCLUDED.per_day, note = EXCLUDED.note;
