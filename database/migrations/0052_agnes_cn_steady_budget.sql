-- Agnes 国内端点的熔断从"并发压测"改成"稳态实测"。
--
-- 0050 那行 40/2400/30000 是按 8 路并发全成功估的：那一次证明的是"这个端点允许并发"，不是
-- "它可以每分钟接 40 个请求"。真上线之后按分钟数它自己的回执（2026-10-10 01:22–01:33）：
--   每分钟成功 5–13 次，成功数最高的那几分钟恰好是失败数为 0 的几分钟（01:25、01:29）；
--   一旦我们发到 30–40 次/分钟，就有 27–34 次被打回 429，重试阶梯再把这一分钟的量进一步推高。
-- 也就是说稳态上限是"每分钟约 10 次"，不是 40。把 per_minute 抬在人家真正能接的数字之上，
-- 买不到吞吐，只买到重试：每一次 429 都要占一次预算、一段退避时间，并把文章往后推。
--
-- 换算到回填：10 次/分钟 ≈ 550 次/小时 ÷ 每篇 5.31 次 ≈ **104 篇/小时 ≈ 2,500 篇/天**。
-- 主端点当日额度恢复后再进池，两把门合计约 180 篇/小时（见 docs/geohot-runbook.md 第 13 节）。
UPDATE budgets SET per_minute = 10, per_hour = 550, per_day = 12000,
       note = '模型调用熔断（Agnes 国内站，按每分钟成功数实测；原 40/2400/30000 是并发压测的误读）'
 WHERE service = 'agnes-cn';
