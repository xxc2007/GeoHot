-- 多模型池的预算行：每个 provider 一行熔断，池里每把 key 只花自己的额度。
--
-- 为什么要新行而不是把 `llm` 那一行调大：`budgets.service` 是熔断的粒度（receipts.ts 按
-- `budget:<service>` 加咨询锁再查这一行），`.com` 与 `.cn` 两个 Agnes 端点是两条独立的对端配额，
-- 合成一行就没法知道是谁在限流；回填跑爆国内端点时也不该把线上实时更新的额度一起吃掉。
--
-- 数值全部来自 2026-10-09 在采集机上对端点本身的实测，不是估的：
--   agnes-cn   单路 1.7–9.0s；8 路并发 8/8 成功、0 次 429、平均 10.9s ⇒ 上限约 44 次/分钟、2640 次/小时。
--              这里取 40/2400/30000，贴着实测略留余量；对照现值 `llm` = 8/420/6000（且实测近 400 次/小时
--              时对方已开始回 429），这一行是回填能按天推进的唯一原因。
--   opencode   该 key 实测 82 个模型里只有 1 个可调用（其余 403 免费档未开通 / 402 无余额），
--              且不支持 JSON 模式，只能承担自由文本调用，因此额度给得很小。
INSERT INTO budgets (service, per_minute, per_hour, per_day, note) VALUES
  ('agnes-cn', 40, 2400, 30000, '模型调用熔断（Agnes 国内站，与 .com 分开计额度）'),
  ('opencode', 10, 300, 3000, '模型调用熔断（OpenCode Zen，当前仅一个可用模型且不支持 JSON 模式）')
ON CONFLICT (service) DO NOTHING;
