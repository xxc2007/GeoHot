-- dots 的日熔断从 6000 抬到 12000（2026-10-12 实测，站长目标要"1 月至今的信息上站"）。
--
-- 为什么这是一条迁移而不只是生产上的一次 UPDATE：0055 把 6000 写进了迁移，
-- 所以任何一次 `npm run db:migrate` 或 AGENTS.md 里那条恢复演练都会把生产值悄悄打回 6000，
-- 站点又会回到"全服务零派发"的状态。可恢复的天花板必须进代码，不能只活在库里。
--
-- 依据（三条都是当天实测，不是推算）：
--   · 抬闸前：六个服务连续 5 分钟零派发；dots 24h 用量 5,989 / 上限 6,000（99.8%）；
--   · 6000→6200 的探针：4 分钟 80 次尝试、80 次成功、提供商侧 0 次 429；
--   · 正式抬到 12000 后：20 分钟 382 次尝试、失败 0，稳定在自设 per_minute=20 上；
--   · 花费：近 24h 6,089 次、31,319,295 tokens，`receipts.cost` 合计 **0** —— 这道闸保护的不是钱。
--
-- per_minute / per_hour 不动：20/分是当前实测的稳态，提供商什么时候开始回 429 只有再抬才知道。
-- 只在不等于旧值时才改，避免盖掉站长之后自己调过的数。
UPDATE budgets SET per_day = 12000, updated_at = now()
 WHERE service = 'dots' AND per_day = 6000;
