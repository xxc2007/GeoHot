#!/bin/bash
# 白天读者优先 / 夜里吃满算力——同一个 worker 进程，两档配置。
#
# 为什么需要这个：2026-11-04 实测这台 891MB / 2 vCPU 的机器，
#   - worker 无约束时首页 15s 回 503（瓶颈是换页，不是 CPU）；
#   - 只把 worker 钉进 MemoryHigh=120M / MemoryMax=200M，首页立刻 0.28–0.84s、0×503，
#     代价是 1 槽 ≈40 条/小时；
#   - 夜里读者极少，可以把内存线与槽位放开，用 ≈171 条/小时的速率啃积压。
#
# 用法：worker-window.sh day|night
#   day   —— MemoryHigh=90M / MemoryMax=150M / MemorySwapMax=128M，COMBINED_LIMIT=2、LANE_LIMIT=2
#   night —— MemoryHigh=260M / MemoryMax=320M / MemorySwapMax=768M，COMBINED_LIMIT=3、LANE_LIMIT=2
#
# 两档都会重启 worker（EnvironmentFile 里的槽位只有重启才生效）；重启本身被 r115 闸门的
# 重启宽限（GRACE=600s）吃掉，不会因为部署/切换自打的 502 反过来停掉进程。
set -euo pipefail

mode=${1:-}
case "$mode" in
  day|night) ;;
  *) echo "usage: $0 day|night" >&2; exit 2 ;;
esac

# 护栏：timer 带 Persistent=true，开机时会把错过的 01:00 补跑一次。
# 如果补跑发生在白天，夜间档（3 槽 + 320M）就会直接顶到读者身上——所以按钟点兜一层。
hour=$(date +%H)
# `date +%H` 给的是 08 / 09 这种带前导零的串，直接进 `[[ -ge ]]` 会被当成八进制：
# 08 不是合法八进制，bash 会报 value too great for base 并中止。强制十进制。
hour=$((10#$hour))
# 护栏：Persistent=true 的补跑可能把 01:00 那次带进白天，所以夜里之外一律降级 day。
# 演练夜间档（白天要验证 01:00 那条路）用 GEOHOT_WINDOW_FORCE=1，它只跳过钟点判断。
if [[ "$mode" == "night" && "$hour" -ge 7 && "${GEOHOT_WINDOW_FORCE:-0}" != "1" ]]; then
  echo "night requested at ${hour}:00, outside the 01:00-07:00 window; falling back to day" >&2
  mode=day
fi

case "$mode" in
  day)
    # 2026-11-05 03:1x 实测：120M/200M/256M 在 891MB 机器上仍会把 swap 顶到 700MB+、首页 503 21s；
    # 白天档再收紧一档，宁可少跑几条，也不让读者页面掉进换页。
    mem_high=90M; mem_max=150M; swap_max=128M
    # 2026-11-05 17:19 现场：两条并行分析（各拉大正文回写）把 loopback 首页拖到 12 秒超时、负载 3.0、
    # 可用内存 89MB；停 worker 5 秒后回到 0.76s。白天只留 1 条分析，本机执行器在线时另算 2 条。
    # 2026-11-05 20:2x 复发（积压 1.07 万、COMBINED=2/LANE=2 时公网 / 与 /all 25 秒 000，loopback 12 秒；
    # 停 worker 后 1.4s/0.47s；只把名额收到 1/1/1、进程不重启地放回来，loopback 1.7s/0.39s 且 CF 3.4s）。
    # 结论：白天在这台机器上，一个名额就是读者体验的上限——多一个名额换来的吞吐抵不过一次换页。
    # 2026-11-06 02:5x 现场：没有任何作业在跑、首页 0.37s，intake 却一直说 resource pressure ——
    # 这台机器 swap 常年 600MB、PSI 的 avg10 一碰 swap 就上 60+，用它当开关等于永远不干活。
    # 白天仍留一条相对紧的线（1 个名额），夜档更松；读者面由 r115 闸门 + 上一份好答案兜住。
    limits=$'GEOHOT_INTAKE_COMBINED_LIMIT=1\nGEOHOT_INTAKE_LANE_LIMIT=1\nGEOHOT_INTAKE_ANALYSIS_SLOTS=1\nGEOHOT_PRESSURE_MEMORY_FULL=70\nGEOHOT_PRESSURE_IO_FULL=80\nGEOHOT_PRESSURE_LOAD_PER_CPU=6\nGEOHOT_RECOVER_MEMORY_FULL=95\nGEOHOT_RECOVER_IO_FULL=95\nGEOHOT_RECOVER_AVAILABLE_MIB=96'
    ;;
  night)
    mem_high=260M; mem_max=320M; swap_max=768M
    # 2026-11-04 22:15 实测：3 槽 + LANE=2 让首页从 0.4s 掉到 15s、两分钟后 503（_diag/t8/night-rehearsal.md）。
    # 这台 891MB / 2 vCPU 的瓶颈是换页，多给内存线有用，多给槽位没用，所以夜里只放到 2 槽。
    # 夜档（国内凌晨）读者最少；压力门的线放到「能干活」为止，真正的刹车是闸门与窗口守护。
    # 2026-11-06 02:5x 现场：memoryFull 80–93、ioFull 90+ 一直挂在压力门上，而 CPU 95% 空转、
    # 首页 0.37s —— 卡住的是门槛，不是机器。
    limits=$'GEOHOT_INTAKE_COMBINED_LIMIT=2\nGEOHOT_INTAKE_LANE_LIMIT=1\nGEOHOT_INTAKE_ANALYSIS_SLOTS=2\nGEOHOT_PRESSURE_MEMORY_FULL=90\nGEOHOT_PRESSURE_IO_FULL=90\nGEOHOT_PRESSURE_LOAD_PER_CPU=8\nGEOHOT_RECOVER_MEMORY_FULL=95\nGEOHOT_RECOVER_IO_FULL=95\nGEOHOT_RECOVER_AVAILABLE_MIB=96'
    ;;
  *)
    echo "usage: $0 day|night" >&2
    exit 2
    ;;
esac

envf=${GEOHOT_WINDOW_ENV:-/etc/geohot/worker-window.env}
{
  echo "# generated by worker-window.sh at $(date -Is) mode=$mode"
  printf '%s\n' "$limits"
} > "$envf"
chmod 640 "$envf"

# set-property 是运行期生效的，不需要 daemon-reload，也不会写坏 drop-in 顺序。
systemctl set-property geohot-worker \
  "MemoryHigh=$mem_high" "MemoryMax=$mem_max" "MemorySwapMax=$swap_max"

# 槽位在 EnvironmentFile 里，只有重启才重新读。
# 但闸门（fence 档）正按着 worker 时不重启：一次 01:00/07:00 的例行切档把冻结解开，
# 等于替读者面把刹车松开（2026-11-06 复核 recovery-paths）。
if [ -e /etc/geohot/readers-only ]; then
  # 2026-11-07 01:00 现场：这台机器标了 readers-only（deploy 与验收都按它判），但夜档窗口
  # 定时器照样 `systemctl restart geohot-worker`，把 worker 拉起来 → 首页 503、验收连挂 4 项。
  # 切档只改内存线与 env，worker 起不起由标记决定。
  echo "window=$mode readers-only: worker left as it is (env written for the next start)"
elif [ -e /run/geohot-r115-fence ]; then
  echo "window=$mode: reader gate holds a fence, worker left as it is (env written for the next start)"
else
  systemctl restart geohot-worker
fi

echo "window=$mode mem_high=$mem_high mem_max=$mem_max swap_max=$swap_max"
systemctl show geohot-worker -p MemoryHigh -p MemoryMax -p MemorySwapMax -p ActiveState |
  tr '\n' ' '
echo

# 读者保护：夜间档是「多给资源」，但这台机器的瓶颈是换页 —— 2026-11-04 22:15 实测：
# 切档瞬间两次探测都合格，90 秒后首页 15s，180 秒后直接 503。所以不能只看两眼就收工。
# 持续观察 GEOHOT_WINDOW_GUARD_WINDOW（默认 180 秒）、每 GEOHOT_WINDOW_GUARD_EVERY（默认 30 秒）探一次；
# **连续** GEOHOT_WINDOW_GUARD_FAILS（默认 2）次非 200 / 超时 / 超过 GEOHOT_WINDOW_GUARD_MS（默认 4000）才退回 day。
#
# 2026-11-06 01:00 现场：夜间档刚切上去，第一次探测正好撞上 worker 重启后的冷页面（503 / 15s），
# 一次就把整个夜档退回白天 —— 那一晚的多余算力全没了。冷启动不该算作「读者被拖慢」，
# 所以先给 15 秒热身、并且要求连续两次不合格。
guard_ms=${GEOHOT_WINDOW_GUARD_MS:-4000}
guard_window=${GEOHOT_WINDOW_GUARD_WINDOW:-180}
guard_every=${GEOHOT_WINDOW_GUARD_EVERY:-30}
guard_fails=${GEOHOT_WINDOW_GUARD_FAILS:-2}
guard_warmup=${GEOHOT_WINDOW_GUARD_WARMUP:-15}
if [[ "${GEOHOT_WINDOW_NO_GUARD:-0}" != "1" && "$mode" == "night" ]]; then
  sleep "$guard_warmup"
  deadline=$(( $(date +%s) + guard_window ))
  bad=0; total=0
  while [ "$(date +%s)" -lt "$deadline" ]; do
    # 探测失败（curl 返回 28/7）不能带崩脚本：显式吞掉退出码。
    probe=$(curl -s -o /dev/null -w "%{http_code} %{time_total}" --max-time 20 http://127.0.0.1:3000/geohot/ 2>/dev/null) || probe="000 99"
    code=${probe%% *}
    secs=${probe##* }
    total=$((total + 1))
    too_slow=$(awk -v s="${secs:-99}" -v g="$guard_ms" 'BEGIN{print (s*1000 > g) ? 1 : 0}')
    if [[ "$code" != "200" || "$too_slow" == "1" ]]; then
      bad=$((bad + 1))
      echo "guard: probe ${code} ${secs}s over $((guard_ms))ms (${bad}/${guard_fails})" >&2
      if [[ "$bad" -ge "$guard_fails" ]]; then break; fi
    else
      bad=0
    fi
    sleep "$guard_every"
  done
  if [[ "$bad" -ge "$guard_fails" ]]; then
    logger -t geohot-window "night window failed the reader guard ${bad} probes in a row; reverting to day"
    echo "guard: reverting to day after ${total} probe(s)" >&2
    GEOHOT_WINDOW_NO_GUARD=1 "$0" day
    exit 0
  fi
  echo "guard: ok (${total} probes within $((guard_ms))ms over ${guard_window}s)"
fi
