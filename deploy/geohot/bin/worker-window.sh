#!/bin/bash
# 白天读者优先 / 夜里吃满算力——同一个 worker 进程，两档配置。
#
# 为什么需要这个：2026-11-04 实测这台 891MB / 2 vCPU 的机器，
#   - worker 无约束时首页 15s 回 503（瓶颈是换页，不是 CPU）；
#   - 只把 worker 钉进 MemoryHigh=120M / MemoryMax=200M，首页立刻 0.28–0.84s、0×503，
#     代价是 1 槽 ≈40 条/小时；
#   - 夜里读者极少，可以把内存线与槽位放开，用 ≈171 条/小时的速率啃积压。
#
# 用法：worker-window.sh day|night
#   day   —— MemoryHigh=120M / MemoryMax=200M / MemorySwapMax=256M，COMBINED_LIMIT=1、LANE_LIMIT=1
#   night —— MemoryHigh=260M / MemoryMax=320M / MemorySwapMax=768M，COMBINED_LIMIT=3、LANE_LIMIT=2
#
# 两档都会重启 worker（EnvironmentFile 里的槽位只有重启才生效）；重启本身被 r115 闸门的
# 重启宽限（GRACE=600s）吃掉，不会因为部署/切换自打的 502 反过来停掉进程。
set -euo pipefail

mode=${1:-}
case "$mode" in
  day|night) ;;
  *) echo "usage: $0 day|night" >&2; exit 2 ;;
esac

# 护栏：timer 带 Persistent=true，开机时会把错过的 01:00 补跑一次。
# 如果补跑发生在白天，夜间档（3 槽 + 320M）就会直接顶到读者身上——所以按钟点兜一层。
hour=$(date +%H)
if [[ "$mode" == "night" && "$hour" -ge 7 ]]; then
  echo "night requested at ${hour}:00, outside the 01:00-07:00 window; falling back to day" >&2
  mode=day
fi

case "$mode" in
  day)
    mem_high=120M; mem_max=200M; swap_max=256M
    limits=$'GEOHOT_INTAKE_COMBINED_LIMIT=1\nGEOHOT_INTAKE_LANE_LIMIT=1'
    ;;
  night)
    mem_high=260M; mem_max=320M; swap_max=768M
    limits=$'GEOHOT_INTAKE_COMBINED_LIMIT=3\nGEOHOT_INTAKE_LANE_LIMIT=2'
    ;;
  *)
    echo "usage: $0 day|night" >&2
    exit 2
    ;;
esac

envf=${GEOHOT_WINDOW_ENV:-/etc/geohot/worker-window.env}
{
  echo "# generated by worker-window.sh at $(date -Is) mode=$mode"
  printf '%s\n' "$limits"
} > "$envf"
chmod 640 "$envf"

# set-property 是运行期生效的，不需要 daemon-reload，也不会写坏 drop-in 顺序。
systemctl set-property geohot-worker \
  "MemoryHigh=$mem_high" "MemoryMax=$mem_max" "MemorySwapMax=$swap_max"

# 槽位在 EnvironmentFile 里，只有重启才重新读。
systemctl restart geohot-worker

echo "window=$mode mem_high=$mem_high mem_max=$mem_max swap_max=$swap_max"
systemctl show geohot-worker -p MemoryHigh -p MemoryMax -p MemorySwapMax -p ActiveState |
  tr '\n' ' '
echo